<script>
    document.addEventListener("DOMContentLoaded", function() {

        const nav = document.querySelector("nav.hidden.md\\:flex");

        if (!nav) return;

        const navLinks = nav.querySelectorAll(".nav-link");


        // =========================
        // PAGE GROUPS
        // =========================

        const pageGroups = {

            company: [
                "about_us.php",
                "strategy.php",
                "our-bank-detail.php"
            ],

            services: [
                "software-development-service.php",
                "mobile-app-development.php",
                "custom-web-application.php",
                "eCommerce-solution.php",
                "web-design-development-services.php",
                "business-intelligence.php",
                "digital-marketing.php",
                "maintenance-support.php"
            ],

            products: [
                // Future product pages
                // "erp-solution.php",
                // "vscrm.php"
            ],

            careers: [
                "career.php"
            ]

        };


        // =========================
        // REMOVE ALL ACTIVE
        // =========================

        function removeAllActive() {

            navLinks.forEach(function(link) {

                link.classList.remove("text-foreground");
                link.classList.add("text-muted-foreground");

                const line = link.querySelector(".active-line");

                if (line) {
                    line.classList.add("hidden");
                }

            });

        }


        // =========================
        // MAKE LINK ACTIVE
        // =========================

        function makeActive(link) {

            if (!link) return;

            removeAllActive();

            link.classList.remove("text-muted-foreground");
            link.classList.add("text-foreground");

            const line = link.querySelector(".active-line");

            if (line) {
                line.classList.remove("hidden");
            }

        }


        // =========================
        // CURRENT PHP PAGE
        // =========================

        const currentPage = window.location.pathname
            .split("/")
            .pop();


        // =========================
        // HOME
        // =========================

        if (
            currentPage === "" ||
            currentPage === "main.php" ||
            currentPage === "index.php"
        ) {

            const home = nav.querySelector(
                '.nav-link[href="main.php"]'
            );

            makeActive(home);
        }


        // =========================
        // COMPANY
        // =========================
        else if (pageGroups.company.includes(currentPage)) {

            const company = nav.querySelector(
                ".dropdown:nth-of-type(1) > .nav-link"
            );

            makeActive(company);
        }


        // =========================
        // SERVICES
        // =========================
        else if (pageGroups.services.includes(currentPage)) {

            const services = nav.querySelector(
                ".dropdown:nth-of-type(2) > .nav-link"
            );

            makeActive(services);
        }


        // =========================
        // PRODUCTS
        // =========================
        else if (pageGroups.products.includes(currentPage)) {

            const products = nav.querySelector(
                ".dropdown:nth-of-type(3) > .nav-link"
            );

            makeActive(products);
        }


        // =========================
        // CAREERS
        // =========================
        else if (pageGroups.careers.includes(currentPage)) {

            const careers = nav.querySelector(
                '.nav-link[href="career.php"]'
            );

            makeActive(careers);
        }


        // =========================
        // NORMAL NAV LINKS
        // =========================

        navLinks.forEach(function(link) {

            link.addEventListener("click", function() {

                // Dropdown parent
                if (this.closest(".dropdown")) {
                    return;
                }

                makeActive(this);

            });

        });


        // =========================
        // DROPDOWN ITEM CLICK
        // =========================

        nav.querySelectorAll(".dropdown-menu a").forEach(function(link) {

            link.addEventListener("click", function() {

                const dropdown = this.closest(".dropdown");

                if (!dropdown) return;

                const parentLink =
                    dropdown.querySelector(":scope > .nav-link");

                makeActive(parentLink);

            });

        });

    });
</script>
